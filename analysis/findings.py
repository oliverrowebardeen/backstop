"""Write analysis/findings.md (lane S3): three plain sentences, regenerable.

Learned order vs the spec's fixed fallback order is compared on the TEST split
(non-trap), with a paired bootstrap over questions (10,000 resamples, seed 14) on
the difference in coverage. Policy for both: ask tavily first, then up to 2
rescue engines in that order; a question is covered if any of those engines hit.
"Beats by more than noise" means the 95 percent interval of the difference
excludes zero.

  python -m analysis.findings
"""
from __future__ import annotations

import numpy as np

from analysis.common import (FAKE, FIXED_ORDER, FIRST_ENGINE, ROOT, hits_by_question, load_rescue_table,
                             need_matrix, split_ids)
from analysis.frontier import MAX_RESCUES

BOOT = 10_000
MIN_MISSES = 5


def covered(h: dict[str, bool], order: list[str]) -> bool:
    return any(h.get(e) for e in [FIRST_ENGINE] + order[:MAX_RESCUES])


def surprising_pair(t: dict, base: dict[str, float]):
    """Largest lift = rescue rate minus the rescuing engine's overall hit rate (learn)."""
    best = None
    for a, row in t["rescue"].items():
        for b, c in row.items():
            if c["misses"] < MIN_MISSES:
                continue
            lift = c["rate"] - base[b]
            if best is None or lift > best[0]:
                best = (lift, a, b, c)
    return best


def main() -> None:
    rows = need_matrix()
    t = load_rescue_table()
    learn = hits_by_question(rows, split_ids("learn"))
    base = {e: float(np.mean([h[e] for h in learn.values() if e in h])) for e in t["rescue"]}
    lift, a, b, c = surprising_pair(t, base)

    test = hits_by_question(rows, split_ids("test"))
    test = {q: h for q, h in test.items() if all(e in h for e in t["rescue"])}
    qs = sorted(test)
    learned = t["order_after"][FIRST_ENGINE]
    yl = np.array([covered(test[q], learned) for q in qs], float)
    yf = np.array([covered(test[q], FIXED_ORDER) for q in qs], float)
    d = yl - yf
    rng = np.random.default_rng(14)
    boots = rng.choice(d, size=(BOOT, len(d))).mean(axis=1)
    lo, hi = np.percentile(boots, [2.5, 97.5])
    n_l, n_f = int((d > 0).sum()), int((d < 0).sum())
    verdict = ("beats the fixed order by more than noise" if lo > 0 else
               "is worse than the fixed order by more than noise" if hi < 0 else
               "does not beat the fixed order by more than noise")

    s1 = (f"On the learn split ({t['n_questions']} questions) {FIRST_ENGINE} missed {t['miss_counts'][FIRST_ENGINE]}, "
          f"and the best single rescue was {t['order_after'][FIRST_ENGINE][0]}, which found the answer in "
          f"{t['rescue'][FIRST_ENGINE][t['order_after'][FIRST_ENGINE][0]]['rescued']} of them.")
    s2 = (f"The most surprising pair is {a} then {b}: {b} found the answer in {c['rescued']} of {c['misses']} "
          f"{a} misses ({c['rate']:.0%}) against a {base[b]:.0%} hit rate overall, "
          f"{'above' if lift > 0 else 'below'} its average by {abs(lift) * 100:.0f} points.")
    s3 = (f"On the test split ({len(qs)} non-trap questions) the learned order ({', '.join(learned[:MAX_RESCUES])}) "
          f"covers {yl.mean():.1%} against {yf.mean():.1%} for the fixed order ({', '.join(FIXED_ORDER[:MAX_RESCUES])}), "
          f"a gap of {(yl.mean() - yf.mean()) * 100:+.1f} points (paired bootstrap 95% interval "
          f"{lo * 100:+.1f} to {hi * 100:+.1f}; {n_l} questions favour learned, {n_f} favour fixed), "
          f"so the learned order {verdict}.")
    head = ("> GENERATED FROM FAKE DATA (SO_FAKE=1). Numbers are placeholders, regenerate on the real matrix "
            "with `python -m analysis.findings`.\n\n" if FAKE else
            "> Generated by `python -m analysis.findings` from the real matrix.\n\n")
    text = head + " ".join([s1, s2, s3]) + "\n"
    (ROOT / "analysis" / "findings.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
